    private void SetMode(int mode)
    {
        ConditionContainer.Visible = mode == 0;
        GeneticsContainer.Visible = mode == 1;
        TraitsContainer.Visible = mode == 2;
        ChemistryContainer.Visible = mode == 3;

        // Update button pressed states to indicate the active tab
