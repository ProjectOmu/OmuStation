    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = base.GetDragModeFor(relativeMousePos);

        if (MinSize.X == MaxSize.X)
        {
            mode &= ~(DragMode.Left | DragMode.Right);
        }

        return mode;
    }

    public void Populate(PlantAnalyzerScannedState state)
    {
        if (state.Status == PlantAnalyzerStatus.NoData)
        {
            ShowNoDataState();
            return;
        }

        if (state.Status == PlantAnalyzerStatus.OutOfRange)
        {
            HandleOutOfRangeState();
            return;
        }

        ResetOutOfRangeState();
        PopulateSeedHeader(state);
        PopulateConditionTab(state);
        PopulateGeneticsTab(state);
        PopulateTraitsTab(state);
        PopulateChemistryTab(state);
    }

    private void ResetOutOfRangeState()
    {
        _outOfRangeSince = null;
        _outOfRangeResetReached = false;
    }

    private void HandleOutOfRangeState()
    {
        if (_outOfRangeResetReached)
        {
            ShowNoDataState();
            return;
        }

        if (_outOfRangeSince == null)
            _outOfRangeSince = DateTime.UtcNow;

        var elapsed = DateTime.UtcNow - _outOfRangeSince.Value;

        if (elapsed >= OutOfRangeReset)
        {
            _outOfRangeResetReached = true;
            _outOfRangeSince = null;
            ShowNoDataState();
        }
        else
        {
            ClearLabels();
            SeedSprite.SetEntity(null);
            SeedSprite.Visible = false;
            OutOfRangeSprite.Visible = true;
            StatusLabel.Text = Loc.GetString("plant-analyzer-window-out-of-range");
        }
    }

    private void PopulateSeedHeader(PlantAnalyzerScannedState state)
    {
        StatusLabel.Text = Loc.GetString("plant-analyzer-window-scanned");
        SeedSprite.Visible = true;
        OutOfRangeSprite.Visible = false;

        SeedNameLabel.Text = state.Name ?? Loc.GetString("plant-analyzer-na");

        if (state.Entity != null)
            SeedSprite.SetEntity(state.Entity.Value);
        else
            SeedSprite.SetEntity((EntityUid?)null);
    }

    private void PopulateConditionTab(PlantAnalyzerScannedState state)
    {
        PopulateHealthBar(state);
        PopulateConditionBars(state);
        PopulateWarnings(state.WarningsText);
        PopulateHarvestIndicator(state.HarvestReady);
    }

    private void PopulateHarvestIndicator(bool harvestReady)
    {
        HarvestReadyIndicator.Visible = false;

        if (!harvestReady)
            return;

        HarvestReadyIndicator.Visible = true;
        HarvestReadyIndicator.FontColorOverride = Color.FromHex(Colors.HealthGreen);
        HarvestReadyIndicator.Text = "⚘ " + Loc.GetString("plant-analyzer-ready-to-harvest");
    }

    private void PopulateHealthBar(PlantAnalyzerScannedState state)
    {
        HealthBar.MaxValue = state.MaxHealth ?? 100;
        HealthBar.Value = state.Health ?? 0;
        HealthBarLabel.Text = FormatHealth(state.Health, state.MaxHealth);
        SetHealthBarColor(state.Health, state.MaxHealth);
    }

    private void PopulateConditionBars(PlantAnalyzerScannedState state)
    {
        PopulateBar(WaterBar, WaterBarLabel, state.Water);
        PopulateBar(NutritionBar, NutritionBarLabel, state.Nutrition);
        PopulateBar(ToxinBar, ToxinBarLabel, state.ToxinLevel);
        PopulateBar(WeedBar, WeedBarLabel, state.WeedLevel);
        PopulateBar(PestBar, PestBarLabel, state.PestLevel);
    }

    private void PopulateBar(ProgressBar bar, Label label, float? value)
    {
        bar.Value = value == null || float.IsNaN(value.Value) || float.IsInfinity(value.Value) ? 0 : value.Value;
        label.Text = FormatPercent(value);
    }

    private void PopulateGeneticsTab(PlantAnalyzerScannedState state)
    {
        PopulateGeneticsStats(state);
        PopulateEnvironmentRequirements(state);
        PopulateMutationTargets(state);
    }

    private void PopulateGeneticsStats(PlantAnalyzerScannedState state)
    {
        YieldMultiplierLabel.Text = state.Yield != null ? state.Yield.Value.ToString() : Loc.GetString("plant-analyzer-na");
        PotencyLabel.Text = state.Potency != null ? ((int)state.Potency.Value).ToString() : Loc.GetString("plant-analyzer-na");
        MaturationLabel.Text = state.Maturation != null ? ((int)state.Maturation.Value).ToString() : Loc.GetString("plant-analyzer-na");
        ProductionLabel.Text = state.Production != null ? ((int)state.Production.Value).ToString() : Loc.GetString("plant-analyzer-na");
        PestResistanceLabel.Text = state.PestResistance != null ? ((int)state.PestResistance.Value).ToString() : Loc.GetString("plant-analyzer-na");
        ToxinResistanceLabel.Text = state.ToxinResistance != null ? ((int)state.ToxinResistance.Value).ToString() : Loc.GetString("plant-analyzer-na");
        WeedResistanceLabel.Text = state.WeedResistance != null ? ((int)state.WeedResistance.Value).ToString() : Loc.GetString("plant-analyzer-na");
    }

    private void PopulateEnvironmentRequirements(PlantAnalyzerScannedState state)
    {
        IdealTemperatureLabel.Text = state.IdealTemperature != null
            ? $"{state.IdealTemperature.Value - 273.15:0.##}°C ± {state.TemperatureTolerance:0.##}°C"
            : Loc.GetString("plant-analyzer-na");

        if (state.LowPressureTolerance != null && state.HighPressureTolerance != null)
        {
            var idealPressure = (state.LowPressureTolerance.Value + state.HighPressureTolerance.Value) / 2f;
            var pressureTolerance = (state.HighPressureTolerance.Value - state.LowPressureTolerance.Value) / 2f;
            IdealPressureLabel.Text = $"{idealPressure:0.##} kPa ± {pressureTolerance:0.##} kPa";
        }
        else
        {
            IdealPressureLabel.Text = Loc.GetString("plant-analyzer-na");
        }

        PopulateGasList(GeneticsConsumedGasesList, state.ConsumedGases, GeneticsConsumedGasesTotalLabel, "plant-analyzer-no-consumed-gases");
    }

    private void PopulateMutationTargets(PlantAnalyzerScannedState state)
    {
        MutationTargetsLabel.Text = state.MutationTargets != null && state.MutationTargets.Count > 0
            ? string.Join("\n", state.MutationTargets.Select(target => TitleCase(target)))
            : Loc.GetString("plant-analyzer-na");
    }

    private void PopulateTraitsTab(PlantAnalyzerScannedState state)
