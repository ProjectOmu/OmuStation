    private void PopulateWarnings(string? warningsText)
    {
        WarningsList.RemoveAllChildren();

        // Update header indicator
        WarningIndicator.Visible = false;

        if (string.IsNullOrWhiteSpace(warningsText))
        {
            WarningsList.AddChild(new Label
            {
                Text = Loc.GetString("plant-analyzer-warnings-none-message"),
                HorizontalExpand = true,
                Align = Label.AlignMode.Left,
                FontColorOverride = Color.FromHex(Colors.TextSecondary)
            });
            return;
        }

        var warningLines = warningsText
            .Split('\n')
            .Select(line => line.Trim())
            .Where(line => !string.IsNullOrEmpty(line))
            .Select(line => line.TrimStart('⚠').Trim())
            .ToList();

        // Show header indicator with count
        if (warningLines.Count > 0)
        {
            WarningIndicator.Visible = true;
            WarningIndicator.Text = $"⚠ {warningLines.Count} {Loc.GetString("plant-analyzer-warnings")}";
        }

        foreach (var warning in warningLines)
        {
            var warningRow = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 0, 0, 4)
            };

            warningRow.AddChild(new Label
            {
                Text = "⚠",
                FontColorOverride = Color.FromHex(Colors.WarningYellow),
                Align = Label.AlignMode.Left,
                VerticalAlignment = VAlignment.Top,
                Margin = new Thickness(0, 0, 6, 0)
            });

            warningRow.AddChild(new RichTextLabel
            {
                Text = warning,
                HorizontalExpand = true,
                VerticalExpand = true
            });

            WarningsList.AddChild(warningRow);
        }
    }

    private static string TitleCase(string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return value;

        try
        {
            return CultureInfo.InvariantCulture.TextInfo.ToTitleCase(value.ToLower(CultureInfo.InvariantCulture));
        }
        catch
        {
            return value;
        }
    }

    private void AddTraitBoxes(BoxContainer list, string? traitText)
    {
        list.RemoveAllChildren();

        // Check for empty/none state before unnecessary string operations
        if (string.IsNullOrWhiteSpace(traitText))
        {
            AddPlaceholderPanel(list, Loc.GetString("plant-analyzer-traits-none"));
            return;
        }

        var trimmedText = traitText.Trim();
        if (trimmedText.Length == 0 || trimmedText == Loc.GetString("plant-analyzer-traits-none"))
        {
            AddPlaceholderPanel(list, Loc.GetString("plant-analyzer-traits-none"));
            return;
        }

        var lines = trimmedText.Split('\n');
        var blocks = new List<(string Name, string Description)>();
        string? currentName = null;
        var currentDescription = new List<string>();

        foreach (var rawLine in lines)
        {
            var line = rawLine.TrimEnd();
            if (line.StartsWith("• "))
            {
                if (currentName != null)
                {
                    blocks.Add((currentName, string.Join("\n", currentDescription).Trim()));
                    currentDescription.Clear();
                }

                currentName = line.Substring(2).Trim();
                continue;
            }

            if (currentName != null)
            {
                if (!string.IsNullOrWhiteSpace(line))
                    currentDescription.Add(line);
            }
            else if (!string.IsNullOrWhiteSpace(line))
            {
                currentName = line.Trim();
            }
        }

        if (currentName != null)
        {
            blocks.Add((currentName, string.Join("\n", currentDescription).Trim()));
        }

        if (blocks.Count == 0)
        {
            AddTraitBoxes(list, null);
            return;
        }

        foreach (var block in blocks)
        {
            var traitPanel = new PanelContainer
            {
                HorizontalExpand = true,
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = Color.FromHex(Colors.PanelBackground),
                    BorderColor = Color.FromHex(Colors.PanelBorder),
                    BorderThickness = new Thickness(1)
                },
                Margin = new Thickness(0)
            };

            var traitBox = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                Margin = new Thickness(8, 8, 8, 8)
            };

            traitBox.AddChild(new Label
            {
                Text = block.Name,
                HorizontalExpand = true,
                FontColorOverride = Color.FromHex(Colors.TextPrimary)
            });

            if (!string.IsNullOrWhiteSpace(block.Description))
            {
                traitBox.AddChild(new RichTextLabel
                {
                    Text = block.Description,
                    HorizontalExpand = true,
                    Margin = new Thickness(0, 4, 0, 0)
                });
            }

            traitPanel.AddChild(traitBox);
            list.AddChild(traitPanel);
        }
    }

    private void PopulateGasList(BoxContainer list, List<PlantReagentEntry>? gases, Label totalLabel, string emptyTextKey)
    {
        list.RemoveAllChildren();
        var totalAmount = gases?.Sum(g => g.Amount) ?? 0f;
        totalLabel.Text = gases != null && gases.Count > 0 ? $"{totalAmount:0.##} moles" : Loc.GetString("plant-analyzer-na");

        if (gases == null || gases.Count == 0)
        {
            AddPlaceholderPanel(list, Loc.GetString(emptyTextKey));
            return;
        }

        for (var i = 0; i < gases.Count; i++)
        {
            AddReagentRow(list, gases[i], i, "moles");
        }
    }

    private void SetHealthBarColor(float? health, float? maxHealth)
    {
        if (HealthBar.ForegroundStyleBoxOverride == null)
        {
            HealthBar.ForegroundStyleBoxOverride = new StyleBoxFlat();
        }

        if (HealthBar.BackgroundStyleBoxOverride == null)
        {
            HealthBar.BackgroundStyleBoxOverride = new StyleBoxFlat();
        }

        var fillColor = (health != null && maxHealth != null && maxHealth > 0)
            ? Color.FromHsv(new Vector4(0.33f * Math.Clamp(health.Value / maxHealth.Value, 0f, 1f), 1f, 0.55f, 1f))
            : Color.FromHex("#444444");

        ((StyleBoxFlat) HealthBar.ForegroundStyleBoxOverride).BackgroundColor = fillColor;
        ((StyleBoxFlat) HealthBar.BackgroundStyleBoxOverride).BackgroundColor = Color.FromHex(Colors.DarkBackground);
    }

    private void AddReagentRow(BoxContainer list, PlantReagentEntry r, int i, string unit = "u")
    {
        var color = Color.FromHex(r.ColorHex);
        var rowColor = i % 2 == 0 ? Color.FromHex(Colors.AlternateRowDark) : Color.FromHex(Colors.DarkerBackground);
        var row = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat { BackgroundColor = rowColor },
            Margin = new Thickness(0, 0, 0, 0)
        };

        var innerRow = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 0)
        };

        var colorPanel = new PanelContainer
        {
            MinWidth = 8,
            VerticalExpand = true,
            PanelOverride = new StyleBoxFlat { BackgroundColor = color },
            Margin = new Thickness(0, 0, 6, 0)
        };

        innerRow.AddChild(colorPanel);
        innerRow.AddChild(new Label { Text = r.Name ?? Loc.GetString("plant-analyzer-unknown-plant"), HorizontalExpand = true, Align = Label.AlignMode.Left });

        var amount = ValidateReagentAmount(r.Amount);
        var display = r.DisplayAmount ?? amount.ToString("0.##");
        var amountText = unit == "moles" ? display + " " + unit : display + unit;

        innerRow.AddChild(new Label { Text = amountText, Align = Label.AlignMode.Right, Margin = new Thickness(0, 0, 6, 0) });
        row.AddChild(innerRow);
        list.AddChild(row);
    }

    /// <summary>
    /// Validate and clamp reagent amount, handling NaN and Infinity values.
    /// </summary>
    private static float ValidateReagentAmount(float amount)
    {
        if (float.IsNaN(amount) || float.IsInfinity(amount))
            return 0f;
        return amount;
    }

    private void SetBarColor(ProgressBar bar, Color color)
    {
        if (bar.ForegroundStyleBoxOverride == null)
        {
            bar.ForegroundStyleBoxOverride = new StyleBoxFlat();
        }

        if (bar.BackgroundStyleBoxOverride == null)
        {
            bar.BackgroundStyleBoxOverride = new StyleBoxFlat();
        }

        ((StyleBoxFlat) bar.ForegroundStyleBoxOverride).BackgroundColor = color;
        ((StyleBoxFlat) bar.BackgroundStyleBoxOverride).BackgroundColor = Color.FromHex(Colors.DarkBackground);
    }

    private static string FormatPercent(float? value)
    {
        if (value == null || float.IsNaN(value.Value) || float.IsInfinity(value.Value))
            return Loc.GetString("plant-analyzer-na");

        return ((int) value.Value).ToString() + "%";
    }

    private static string FormatHealth(float? health, float? maxHealth)
    {
        if (health == null || maxHealth == null || maxHealth == 0 || float.IsNaN(health.Value) || float.IsNaN(maxHealth.Value))
            return Loc.GetString("plant-analyzer-na");

        var percent = (int)(Math.Clamp(health.Value / maxHealth.Value, 0f, 1f) * 100f);
        return percent.ToString() + "%";
    }

