        PopulateGases(state);
    }

    private void PopulateReagents(PlantAnalyzerScannedState state)
    {
        var inherentList = state.InherentReagents ?? new List<PlantReagentEntry>();
        var mutatedList = state.MutatedReagents ?? new List<PlantReagentEntry>();
        var totalReagentsAmount = inherentList.Sum(r => r.Amount) + mutatedList.Sum(r => r.Amount);

        TotalReagentsLabel.Text = (inherentList.Count > 0 || mutatedList.Count > 0)
            ? $"{totalReagentsAmount:0.##}u"
            : Loc.GetString("plant-analyzer-na");

        PopulateReagentList(InherentReagentsList, inherentList, InherentReagentsTotalLabel, "plant-analyzer-no-base-reagents");
        PopulateReagentList(MutatedReagentsList, mutatedList, MutatedReagentsTotalLabel, "plant-analyzer-no-additional-reagents");
    }

    private void PopulateReagentList(BoxContainer container, List<PlantReagentEntry> reagents, Label totalLabel, string emptyTextKey)
    {
        container.RemoveAllChildren();
        var total = reagents.Sum(r => r.Amount);
        totalLabel.Text = reagents.Count > 0 ? $"{total:0.##}u" : Loc.GetString("plant-analyzer-na");

        if (reagents.Count == 0)
        {
            AddPlaceholderPanel(container, Loc.GetString(emptyTextKey));
            return;
        }

        for (var i = 0; i < reagents.Count; i++)
        {
            AddReagentRow(container, reagents[i], i);
        }
    }

