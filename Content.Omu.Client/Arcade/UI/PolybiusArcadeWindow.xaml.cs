using Content.Client.Resources;
using Content.Client.UserInterface.Controls;
using Content.Shared.Dataset;
using Content.Shared.Random.Helpers;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Random;
using Robust.Shared.Timing;

namespace Content.Omu.Client.Arcade.UI;

[GenerateTypedNameReferences]
public sealed partial class PolybiusArcadeWindow : FancyWindow
{
    private const float GlitchSeconds = 0.25f;
    private const float SubliminalSeconds = 0.034f;
    private const string SubliminalFont = "/Fonts/_Omu/Sixtyfour/Sixtyfour-Regular.ttf";
    private const int ProbeFontSize = 44;
    private const float MaxTextWidth = 424f;
    private const float MaxTextHeight = 504f;
    private const float MaxGlyphPixels = 240f;

    private static readonly ProtoId<LocalizedDatasetPrototype> Subliminals = "PolybiusSubliminals";

    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IRobustRandom _random = default!;
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    public event Action? OnScreenDied;

    private float? _secondsSincePlay;
    private float _subliminalEnd;

    public PolybiusArcadeWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PlayButton.OnPressed += _ => StartDying();
    }

    private void StartDying()
    {
        PlayButton.Disabled = true;
        TitleScreen.Visible = false;
        GlitchScreen.Visible = true;
        PickSubliminal();
        _secondsSincePlay = 0f;
    }

    private void PickSubliminal()
    {
        var lines = _random.Pick(_prototype.Index(Subliminals)).Split(' ');
        SubliminalLabel.Text = string.Join('\n', lines);

        var probe = _resourceCache.GetFont(SubliminalFont, ProbeFontSize);
        var widestLine = 1f;
        var largestGlyph = 1f;

        foreach (var line in lines)
        {
            var width = 0f;
            foreach (var rune in line.EnumerateRunes())
            {
                if (!probe.TryGetCharMetrics(rune, 1f, out var metrics))
                    continue;

                width += metrics.Advance;
                largestGlyph = MathF.Max(largestGlyph, MathF.Max(metrics.Width, metrics.Height));
            }

            widestLine = MathF.Max(widestLine, width);
        }

        var fill = MathF.Min(MaxTextWidth / widestLine, MaxTextHeight / (probe.GetLineHeight(1f) * lines.Length));
        var scale = MathF.Min(fill, MaxGlyphPixels / (UIScale * largestGlyph));
        SubliminalLabel.FontOverride = _resourceCache.GetFont(SubliminalFont, (int) (ProbeFontSize * scale));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_secondsSincePlay is not { } elapsed)
            return;

        elapsed += args.DeltaSeconds;
        _secondsSincePlay = elapsed;

        if (elapsed < GlitchSeconds)
            return;

        GlitchScreen.Visible = false;

        if (!SubliminalLabel.Visible)
        {
            SubliminalLabel.Visible = true;
            _subliminalEnd = elapsed + SubliminalSeconds;
            return;
        }

        if (elapsed < _subliminalEnd)
            return;

        SubliminalLabel.Visible = false;
        _secondsSincePlay = null;
        OnScreenDied?.Invoke();
    }
}
