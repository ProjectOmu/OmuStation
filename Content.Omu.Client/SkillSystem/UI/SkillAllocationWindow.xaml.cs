using System.Linq;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Omu.Shared.SkillSystem;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Omu.Client.SkillSystem.UI;

[GenerateTypedNameReferences]
public sealed partial class SkillAllocationWindow : FancyWindow
{
    public event Action<Dictionary<string, int>>? OnConfirmed;

    private readonly List<SkillRow> _rows = new();
    private int _points;

    public SkillAllocationWindow()
    {
        RobustXamlLoader.Load(this);

        ConfirmButton.OnPressed += _ => OnConfirmed?.Invoke(_rows.ToDictionary(row => row.Id, row => row.Allocated));
    }

    public void UpdateState(SkillAllocationBoundUserInterfaceState state)
    {
        _points = state.Points;
        _rows.Clear();
        Skills.DisposeAllChildren();

        foreach (var skill in state.Skills)
            AddRow(skill);

        Refresh();
    }

    private void AddRow(SkillAllocationEntry skill)
    {
        var row = new SkillRow(skill.Id, skill.Level);
        row.Minus.OnPressed += _ => Adjust(row, -1);
        row.Plus.OnPressed += _ => Adjust(row, 1);

        Skills.AddChild(new Label
        {
            Text = Loc.GetString(skill.Name),
            ToolTip = skill.Description is { } description ? Loc.GetString(description) : null,
            MouseFilter = MouseFilterMode.Pass,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        });
        Skills.AddChild(row.Bar);
        Skills.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Children = { row.Minus, row.LevelLabel, row.Plus },
        });
        _rows.Add(row);
    }

    private void Adjust(SkillRow row, int delta)
    {
        row.Allocated += delta;
        Refresh();
    }

    private void Refresh()
    {
        var remaining = _points - _rows.Sum(row => row.Allocated);

        foreach (var row in _rows)
        {
            row.Bar.SetLevels(row.Level, row.Allocated);
            row.Bar.ToolTip = row.Allocated > 0
                ? Loc.GetString("skill-allocation-level-raised",
                    ("level", row.Level),
                    ("raised", row.Level + row.Allocated))
                : Loc.GetString("skill-allocation-level", ("level", row.Level));
            row.LevelLabel.Text = (row.Level + row.Allocated).ToString();
            row.Minus.Disabled = row.Allocated == 0;
            row.Plus.Disabled = remaining == 0;
        }

        PointsLabel.Text = remaining.ToString();
        PointsBadge.RemoveStyleClass(remaining == 0 ? StyleClass.Highlight : StyleClass.Positive);
        PointsBadge.AddStyleClass(remaining == 0 ? StyleClass.Positive : StyleClass.Highlight);
        EmptyLabel.Visible = _rows.Count == 0;
        HintLabel.Visible = _rows.Count > 0 && remaining > 0;
        ConfirmButton.Disabled = _rows.Count == 0 || remaining > 0;
    }

    private sealed class SkillRow(string id, int level)
    {
        public readonly string Id = id;
        public readonly int Level = level;
        public int Allocated;
        public readonly SkillLevelBar Bar = new();
        public readonly Label LevelLabel = new()
        {
            MinWidth = 36,
            Align = Label.AlignMode.Center,
            VerticalAlignment = VAlignment.Center,
        };
        public readonly Button Minus = new() { Text = "-", StyleClasses = { StyleClass.ButtonOpenRight } };
        public readonly Button Plus = new() { Text = "+", StyleClasses = { StyleClass.ButtonOpenLeft } };
    }
}
