using System.Numerics;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Omu.Shared.Billiards;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Omu.Client.Billiards.UI;

[GenerateTypedNameReferences]
public sealed partial class BilliardsWindow : FancyWindow
{
    private const float CalloutSeconds = 1.8f;
    private const int PlateColumns = 4;
    private const float PlatesTop = 16f;
    private const float CompactPlatesTop = 3f;
    private static readonly Vector2 CardSize = new(170f, 58f);

    private readonly Dictionary<BilliardsMode, Button> _cards = [];

    private float _calloutLeft;
    private BilliardsMode _mode;

    public event Action<Vector2, float>? OnAim;
    public event Action<Vector2, float>? OnShoot;
    public event Action<Vector2>? OnPlace;
    public event Action<BilliardsMode>? OnNewGame;
    public event Action? OnJoin;
    public event Action? OnLeave;
    public event Action? OnSkip;

    public BilliardsWindow()
    {
        RobustXamlLoader.Load(this);

        foreach (var mode in Enum.GetValues<BilliardsMode>())
        {
            if (mode == BilliardsMode.Unselected)
                continue;

            var card = CreateCard(mode);
            _cards[mode] = card;
            ModeCards.AddChild(card);
        }

        TableView.OnAim += (direction, power) =>
        {
            ShowPower(power);
            OnAim?.Invoke(direction, power);
        };
        TableView.OnShoot += (direction, power) => OnShoot?.Invoke(direction, power);
        TableView.OnPlace += spot => OnPlace?.Invoke(spot);
        JoinButton.OnPressed += _ => OnJoin?.Invoke();
        LeaveButton.OnPressed += _ => OnLeave?.Invoke();
        SkipButton.OnPressed += _ => OnSkip?.Invoke();
        NewGameButton.OnPressed += _ => ModeMenu.Visible = true;
        RestartButton.OnPressed += _ => OnNewGame?.Invoke(_mode);
        MenuBackButton.OnPressed += _ => ModeMenu.Visible = false;
    }

    public void SetTable(EntityUid table)
    {
        TableView.Table = table;
    }

    public void SetAim(bool canAim, bool ballInHand, float power)
    {
        TableView.SetTurn(canAim, ballInHand);
        ShowPower(power);
    }

    public void SetPocketed(int pocketed, int total)
    {
        Pocketed.Text = Loc.GetString("billiards-window-pocketed-count", ("count", pocketed), ("total", total));
    }

    public void SetMode(BilliardsMode mode)
    {
        if (mode == BilliardsMode.Unselected)
            ModeMenu.Visible = true;
        else if (_mode == BilliardsMode.Unselected)
            ModeMenu.Visible = false;

        _mode = mode;
        MenuBackButton.Visible = mode != BilliardsMode.Unselected;
        foreach (var (cardMode, card) in _cards)
        {
            card.Pressed = cardMode == mode;
        }

        LobbyTitle.Text = Loc.GetString(ModeName(mode));
        LobbySubtitle.Text = Loc.GetString(ModeDescription(mode));
    }

    public void SetPlayers(IReadOnlyList<BilliardsPlayer> players,
        IReadOnlyList<int> groupBalls,
        int lifeSlots,
        int turn)
    {
        while (Plates.ChildCount > players.Count)
        {
            Plates.RemoveChild(Plates.ChildCount - 1);
        }

        while (Plates.ChildCount < players.Count)
        {
            Plates.AddChild(new BilliardsPlate());
        }

        var compact = players.Count > PlateColumns;
        for (var index = 0; index < players.Count; index++)
        {
            var plate = (BilliardsPlate) Plates.GetChild(index);
            plate.SetPlayer(players[index], groupBalls[index], lifeSlots, index == turn, compact);
        }

        Plates.Columns = Math.Clamp(players.Count, 1, PlateColumns);
        Plates.Margin = new Thickness(0, compact ? CompactPlatesTop : PlatesTop, 0, 0);
        Lobby.Visible = players.Count == 0 && _mode != BilliardsMode.Unselected;
    }

    public void SetActions(bool joinable, bool playing, bool canJoin, bool canLeave, bool canSkip, bool canStart)
    {
        JoinButton.Visible = joinable && !playing;
        JoinButton.Disabled = !canJoin;
        LeaveButton.Visible = playing;
        LeaveButton.Disabled = !canLeave;
        SkipButton.Visible = playing;
        SkipButton.Disabled = !canSkip;
        var canRestart = canStart && _mode != BilliardsMode.Unselected;
        NewGameButton.Visible = canRestart;
        RestartButton.Visible = canRestart;

        foreach (var card in _cards.Values)
        {
            card.Disabled = !canStart;
        }

        if (!canStart && _mode != BilliardsMode.Unselected)
            ModeMenu.Visible = false;
    }

    public void ShowCallout(string text)
    {
        CalloutText.Text = text;
        Callout.Visible = true;
        _calloutLeft = CalloutSeconds;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!Callout.Visible)
            return;

        _calloutLeft -= args.DeltaSeconds;
        if (_calloutLeft <= 0f)
            Callout.Visible = false;
    }

    private static string ModeName(BilliardsMode mode)
    {
        return mode switch
        {
            BilliardsMode.Casual => "billiards-mode-casual",
            BilliardsMode.SolidsStripes => "billiards-mode-solids-stripes",
            BilliardsMode.Killer => "billiards-mode-killer",
            BilliardsMode.FewestShots => "billiards-mode-fewest-shots",
            _ => "billiards-mode-freeplay",
        };
    }

    private static string ModeDescription(BilliardsMode mode)
    {
        return mode switch
        {
            BilliardsMode.Casual => "billiards-mode-casual-desc",
            BilliardsMode.SolidsStripes => "billiards-mode-solids-stripes-desc",
            BilliardsMode.Killer => "billiards-mode-killer-desc",
            BilliardsMode.FewestShots => "billiards-mode-fewest-shots-desc",
            _ => "billiards-mode-freeplay-desc",
        };
    }

    private static string PlayerRange(BilliardsMode mode)
    {
        var limit = SharedBilliardsTableSystem.PlayerLimit(mode);
        return limit switch
        {
            0 => Loc.GetString("billiards-players-anyone"),
            1 => Loc.GetString("billiards-players-solo"),
            _ => Loc.GetString("billiards-players-range", ("max", limit)),
        };
    }

    private Button CreateCard(BilliardsMode mode)
    {
        var card = new Button
        {
            ToggleMode = true,
            MinSize = CardSize,
            ToolTip = Loc.GetString(ModeDescription(mode)),
        };

        card.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(8, 4),
            VerticalAlignment = VAlignment.Center,
            Children =
            {
                new Label { Text = Loc.GetString(ModeName(mode)), StyleClasses = { StyleClass.LabelHeading } },
                new Label { Text = PlayerRange(mode), StyleClasses = { StyleClass.LabelSubText } },
            },
        });

        card.OnPressed += _ =>
        {
            card.Pressed = mode == _mode;
            ModeMenu.Visible = false;
            OnNewGame?.Invoke(mode);
        };

        return card;
    }

    private void ShowPower(float power)
    {
        PowerValue.Text = Loc.GetString("billiards-window-power-value", ("power", (int) MathF.Round(power * 100f)));
    }
}
