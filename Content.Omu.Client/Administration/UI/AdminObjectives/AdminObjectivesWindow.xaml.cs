using Content.Client.UserInterface.Controls;
using Content.Omu.Client.Administration.UI.AdminObjectives.Components;
using Content.Shared.Mind;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Player;
using Robust.Shared.Prototypes;

namespace Content.Omu.Client.Administration.UI.AdminObjectives;

[GenerateTypedNameReferences]
public sealed partial class AdminObjectivesWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    public AdminObjectivesWindow(AdminObjectivesWindowModel model) : this()
    {
        UpdateUi(model);
    }

    public AdminObjectivesWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    public void UpdateUi(AdminObjectivesWindowModel model)
    {
        CharacterIcon.SetEntity(model.Character);
        CharacterName.Text = model.CharacterName;

        var roleType = _prototypeManager.Index(model.RoleTypeId);
        RoleType.Text = Loc.GetString(roleType.Name);
        RoleType.FontColorOverride = roleType.Color;

        if (model.RoleTypeSubType.HasValue)
            RoleTypeSubType.Text = Loc.GetString(model.RoleTypeSubType);
        RoleTypeSubType.FontColorOverride = roleType.Color;

        Objectives.RemoveAllChildren();
        foreach (var objectiveList in model.Objectives)
        {
            Objectives.AddChild(new AdminObjectiveGroup(new AdminObjectiveGroup.Model(objectiveList.Key, objectiveList.Value)));
        }

        if (model.Targets.Count > 0)
            Objectives.AddChild(new AdminObjectiveGroup(new AdminObjectiveGroup.Model(Loc.GetString("admin-view-objectives-window-sacrifice-targets"), model.Targets)));
    }
}

public sealed record AdminObjectivesWindowModel(Entity<ActorComponent> Character, string CharacterName, ProtoId<RoleTypePrototype> RoleTypeId, LocId? RoleTypeSubType, Dictionary<string, List<AdminObjectiveItem.Model>> Objectives, List<AdminObjectiveItem.Model> Targets);
