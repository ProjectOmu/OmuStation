using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Omu.Client.Administration.UI.Components.Target;

[GenerateTypedNameReferences]
public sealed partial class AdminTargetGroup : Control
{
    public AdminTargetGroup(AdminTargetGroupModel model) : this()
    {
        SetTargets(model);
    }

    public AdminTargetGroup()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetTargets(AdminTargetGroupModel model)
    {
        Title.SetMarkupPermissive(model.Title);

        foreach (var target in model.Targets)
        {
            Objectives.AddChild(new AdminTargetItem(target));
        }
    }

    public record AdminTargetGroupModel(string Title, List<AdminTargetItem.AdminTargetItemModel> Targets);
}

