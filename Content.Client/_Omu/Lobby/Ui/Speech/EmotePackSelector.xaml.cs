namespace Content.Client._Omu.Lobby.Ui.Speech;

[GenerateTypedNameReferences]
public sealed partial class EmotePackSelector : BoxContainer
{
    [Dependency] private readonly IComponentFactory _factory = default!;
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IRobustRandom _random = default!;

    private readonly List<(EmotePackPrototype? Pack, ProtoId<SpeciesPrototype> Species)> _entries = new();
    private Sex _sex;
    private ProtoId<SpeciesPrototype> _species;

    public event Action<ProtoId<EmotePackPrototype>?, ProtoId<SpeciesPrototype>?>? OnPackSelected;

    public EmotePackSelector()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        PackButton.OnItemSelected += args =>
        {
            PackButton.SelectId(args.Id);
            var (pack, species) = _entries[args.Id];
            OnPackSelected?.Invoke(pack?.ID, species == _species ? null : (ProtoId<SpeciesPrototype>?) species);
            PlayPreview();
        };
        PlayButton.OnPressed += _ => PlayPreview();
    }

    public void SetProfile(HumanoidCharacterProfile? profile)
    {
        _entries.Clear();
        PackButton.Clear();
        Visible = false;

        if (profile == null)
            return;

        _sex = profile.Sex;
        _species = profile.Species;
        var sounds = EmotePackRules.SpeciesSounds(_proto, _factory, _species);
        var own = EmotePackRules.PacksFor(_proto, _factory, _species)
            .OrderBy(pack => Loc.GetString(pack.Name))
            .ToList();
        var matching = own.FindIndex(pack => pack.SoundsFor(_sex, sounds) is [var set]
            && set == sounds.GetValueOrDefault(_sex));

        if (matching < 0)
            _entries.Add((null, _species));
        _entries.AddRange(own.Select(pack => ((EmotePackPrototype?) pack, _species)));

        var unlocked = _proto.EnumeratePrototypes<SpeciesPrototype>()
            .Where(species => species.RoundStart
                && species.ID != _species
                && VoiceUnlockPrototype.IsUnlocked(_proto, profile, species.ID, emotePack: true))
            .OrderBy(species => Loc.GetString(species.Name));
        foreach (var species in unlocked)
        {
            _entries.AddRange(EmotePackRules.PacksFor(_proto, _factory, species.ID)
                .OrderBy(pack => Loc.GetString(pack.Name))
                .Select(pack => ((EmotePackPrototype?) pack, new ProtoId<SpeciesPrototype>(species.ID))));
        }

        if (_entries.Count < 2)
            return;

        for (var i = 0; i < _entries.Count; i++)
        {
            PackButton.AddItem(Label(_entries[i]), i);
        }

        var selected = EmotePackRules.TryGetChoice(_proto, _factory, profile, out var chosen, out var source)
            ? _entries.FindIndex(entry => entry.Pack == chosen && entry.Species == source)
            : matching;
        PackButton.SelectId(Math.Max(selected, 0));
        Visible = true;
    }

    private string Label((EmotePackPrototype? Pack, ProtoId<SpeciesPrototype> Species) entry)
    {
        if (entry.Pack is not { } pack)
            return Loc.GetString("emote-pack-default");

        if (entry.Species == _species)
            return Loc.GetString(pack.Name);

        return Loc.GetString("emote-pack-borrowed",
            ("species", Loc.GetString(_proto.Index(entry.Species).Name)),
            ("pack", Loc.GetString(pack.Name)));
    }

    private bool CanUse(EmotePrototype emote, EntityPrototype mob)
    {
        if (mob.TryGetComponent<SpeechComponent>(out var speech, _factory) && speech.AllowedEmotes.Contains(emote.ID))
            return true;

        return emote.Available
            && (emote.Whitelist is not { } whitelist || Matches(whitelist, mob))
            && (emote.Blacklist is not { } blacklist || !Matches(blacklist, mob));
    }

    private bool Matches(EntityWhitelist list, EntityPrototype mob)
    {
        var tags = mob.TryGetComponent<TagComponent>(out var tag, _factory)
            ? tag.Tags
            : new HashSet<ProtoId<TagPrototype>>();
        var hits = (list.Components ?? []).Select(mob.Components.ContainsKey)
            .Concat((list.Tags ?? []).Select(tags.Contains))
            .ToList();
        return list.RequireAll ? hits.All(hit => hit) : hits.Any(hit => hit);
    }

    private void PlayPreview()
    {
        var (pack, species) = _entries[PackButton.SelectedId];
        var speciesSounds = EmotePackRules.SpeciesSounds(_proto, _factory, species);
        List<ProtoId<EmoteSoundsPrototype>> sets = pack != null
            ? pack.SoundsFor(_sex, speciesSounds)
            : speciesSounds.TryGetValue(_sex, out var own) ? new() { own } : new();
        if (sets.Count == 0 || !_proto.TryIndex(_random.Pick(sets), out var sounds))
            return;

        var mobs = new[] { EmotePackRules.SpeciesMob(_proto, _species), EmotePackRules.SpeciesMob(_proto, species) }
            .OfType<EntityPrototype>()
            .ToList();
        var vocal = sounds.Sounds
            .Where(pair => _proto.TryIndex(pair.Key, out var emote)
                && emote.Category.HasFlag(EmoteCategory.Vocal)
                && emote.ChatTriggers.Count > 0
                && mobs.Any(mob => CanUse(emote, mob)))
            .Select(pair => pair.Value)
            .ToList();
        if (vocal.Count == 0)
            return;

        _entManager.System<SharedAudioSystem>()
            .PlayGlobal(_random.Pick(vocal), Filter.Local(), false, sounds.GeneralParams);
    }
}
