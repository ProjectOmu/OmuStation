using System.Linq;
using System.Numerics;
using Content.Client.Stylesheets;
using Content.Omu.Common.CCVar;
using Content.Shared._Omu.SkillSystem;
using Content.Shared.Preferences;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;

namespace Content.Client._Omu.Lobby.Ui.Skills;

[GenerateTypedNameReferences]
public sealed partial class SkillsTab : BoxContainer
{
    public event Action<Dictionary<ProtoId<SkillNamePrototype>, int>>? OnAllocationChanged;

    private readonly IPrototypeManager _prototypeManager;
    private readonly List<SkillRow> _rows = new();
    private readonly int _points;
    private List<ProtoId<JobPrototype>> _topJobs = new();

    private bool IsComplete => Remaining <= 0;

    private int Remaining => _points - _rows.Sum(row => row.Allocated);

    public SkillsTab(IConfigurationManager configManager, IPrototypeManager prototypeManager)
    {
        RobustXamlLoader.Load(this);

        _prototypeManager = prototypeManager;
        _points = configManager.GetCVar(OmuCVars.SkillAllocationPoints);
        foreach (var skill in prototypeManager.EnumeratePrototypes<SkillNamePrototype>().OrderBy(skill => skill.ID))
        {
            AddRow(skill);
        }

        Refresh();
    }

    public void SetProfile(HumanoidCharacterProfile? profile)
    {
        foreach (var row in _rows)
        {
            row.Allocated = profile?.SkillAllocation.GetValueOrDefault(row.Id) ?? 0;
        }

        var priorities = profile?.JobPriorities;
        _topJobs = priorities is { Count: > 0 }
            ? priorities.Where(job => job.Value == priorities.Values.Max()).Select(job => job.Key).ToList()
            : new();
        Refresh();
    }

    private bool AppliesToTopJobs(SkillRow row)
    {
        return row.JobDepartments.Count == 0 ||
            (_topJobs.Count > 0 && _topJobs.All(job => row.JobDepartments.Any(department =>
                _prototypeManager.Index(department).Roles.Contains(job))));
    }

    private void AddRow(SkillNamePrototype skill)
    {
        var row = new SkillRow(skill.ID, skill.JobDepartments);
        row.Minus.OnPressed += _ => Adjust(row, -1);
        row.Plus.OnPressed += _ => Adjust(row, 1);
        row.Warning.ToolTip = Loc.GetString("skill-allocation-department-warning",
            ("departments", string.Join(", ", skill.JobDepartments.Select(department =>
                Loc.GetString(_prototypeManager.Index(department).Name)))));

        Skills.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 4,
            Children =
            {
                new Label
                {
                    Text = Loc.GetString(skill.Name),
                    ToolTip = skill.Description is { } description ? Loc.GetString(description) : null,
                    MouseFilter = MouseFilterMode.Pass,
                    VerticalAlignment = VAlignment.Center,
                },
                row.Warning,
            },
        });
        Skills.AddChild(row.Bar);
        Skills.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Children = { row.Minus, row.LevelLabel, row.Plus },
        });
        _rows.Add(row);
    }

    private void Adjust(SkillRow row, int delta)
    {
        row.Allocated += delta;
        Refresh();
        OnAllocationChanged?.Invoke(_rows.Where(r => r.Allocated > 0).ToDictionary(r => r.Id, r => r.Allocated));
    }

    private void Refresh()
    {
        var remaining = Remaining;

        foreach (var row in _rows)
        {
            row.Bar.SetLevels(row.Allocated, 0);
            row.Bar.ToolTip = Loc.GetString("skill-allocation-level", ("level", row.Allocated));
            row.LevelLabel.Text = row.Allocated.ToString();
            row.Minus.Disabled = row.Allocated == 0;
            row.Plus.Disabled = remaining <= 0;
            row.Warning.Visible = !AppliesToTopJobs(row);
        }

        PointsLabel.Text = Math.Max(remaining, 0).ToString();
        PointsBadge.RemoveStyleClass(IsComplete ? StyleClass.Highlight : StyleClass.Positive);
        PointsBadge.AddStyleClass(IsComplete ? StyleClass.Positive : StyleClass.Highlight);
        EmptyLabel.Visible = _rows.Count == 0;
        AlertTabContainer.SetTabAlert(this, !IsComplete);
    }

    private sealed class SkillRow(ProtoId<SkillNamePrototype> id, List<ProtoId<DepartmentPrototype>> jobDepartments)
    {
        public readonly ProtoId<SkillNamePrototype> Id = id;
        public readonly List<ProtoId<DepartmentPrototype>> JobDepartments = jobDepartments;
        public int Allocated;
        public readonly SkillLevelBar Bar = new();
        public readonly Label LevelLabel = new()
        {
            MinWidth = 36,
            Align = Label.AlignMode.Center,
            VerticalAlignment = VAlignment.Center,
        };
        public readonly Button Minus = new() { Text = "-", StyleClasses = { StyleClass.ButtonOpenRight } };
        public readonly Button Plus = new() { Text = "+", StyleClasses = { StyleClass.ButtonOpenLeft } };
        public readonly TextureRect Warning = new()
        {
            TexturePath = "/Textures/Interface/Nano/lock.svg.192dpi.png",
            TextureScale = new Vector2(0.4f, 0.4f),
            Stretch = TextureRect.StretchMode.KeepCentered,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Stop,
            Visible = false,
        };
    }
}
